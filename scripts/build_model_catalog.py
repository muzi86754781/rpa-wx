"""Create the bundled factual model-ID snapshot from locally collected official docs."""
import json
from pathlib import Path
import pprint
import re

ROOT = Path(__file__).resolve().parents[1]
EXTRACTED = ROOT / '.local' / 'catalog-sources' / 'extracted.json'
DATE = '2026-11-04'


def reviewed_id(value):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._/-]{1,199}', value) or '-' not in value:
        return False
    if value[0].isupper() and not value.startswith(('MiniMax-', 'MiniMax/', 'ZHIPU/', 'Tripo/', 'FLUX')):
        return False  # Display family headings are not case-sensitive API IDs.
    if value in ('qwen3-coder', 'deepseek-v4', 'text-embedding-3-large') or value.endswith(('-realtime-', '.py', '.json', '.js', '.png', '.jpg')):
        return False
    return True


if __name__ == '__main__':
    entries = json.loads(EXTRACTED.read_text(encoding='utf-8'))
    groups = [(entry['source'].rsplit('/', 1)[-1], tuple(value for value in entry.get('ids', []) if reviewed_id(value)))
              for entry in entries if entry.get('ids')]
    groups = [(slug, ids) for slug, ids in groups if ids]
    text = ('"""Official Alibaba model IDs; generated by scripts/build_model_catalog.py.\n'
            'Factual snapshot, not an assertion of account access or free credits.\n"""\n'
            + 'CATALOG_DATE = ' + repr(DATE) + '\nCATALOG_GROUPS = '
            + pprint.pformat(tuple(groups), width=115, sort_dicts=False) + '\n')
    (ROOT / 'catalog_data.py').write_text(text, encoding='utf-8')
    ids = sorted({value for _, values in groups for value in values})
    print('Bundled models:', len(ids), 'official source pages:', len(groups))
